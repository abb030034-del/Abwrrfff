def _normalize_arabic(text: str) -> str:
    if not text:
        return ""
    # Strip diacritics
    text = unicodedata.normalize("NFKD", text)
    text = "".join(c for c in text if not unicodedata.combining(c))
    # Letter normalization
    repl = {
        "ة": "ه",
        "إ": "ا",
        "أ": "ا",
        "آ": "ا",
        "ٱ": "ا",
        "ى": "ي",
        "ؤ": "و",
        "ئ": "ي",
        "ـ": "",  # tatweel
    }
    for k, v in repl.items():
        text = text.replace(k, v)
    text = text.strip().lower()
    # Collapse multiple spaces
    text = " ".join(text.split())
    return text


# Build a lookup map from normalized variant → (display_name, url)
_LOOKUP = {}
for display, variants, msg_id in SURAHS:
    url = f"{BASE}/{msg_id}"
    _LOOKUP[_normalize_arabic(display)] = (display, url)
    for v in variants:
        _LOOKUP[_normalize_arabic(v)] = (display, url)


def _resolve_surah(query: str):
    """Resolve a user-provided surah name to (display, url) or None."""
    if not query:
        return None
    q = _normalize_arabic(query)
    if not q:
        return None
    if q in _LOOKUP:
        return _LOOKUP[q]
    # Try stripping leading "ال"
    if q.startswith("ال"):
        q2 = q[2:]
        if q2 in _LOOKUP:
            return _LOOKUP[q2]
    # Try prepending "ال"
    q3 = "ال" + q
    if q3 in _LOOKUP:
        return _LOOKUP[q3]
    return None


def register_quran_handler(app: Client):

    @app.on_message(filters.regex(r"^سور[ةه]\s+(.+)$"))
    async def surah_command(client, message: Message):
        try:
            name = message.matches[0].group(1).strip()
        except Exception:
            return
        if not name:
            return

        resolved = _resolve_surah(name)
        if not resolved:
            return await message.reply_text(
                "⚠️ لم أتعرف على اسم السورة.\nتأكد من الكتابة، مثال: ( سورة الفاتحة )"
            )

        display, url = resolved
        buttons = InlineKeyboardMarkup(
            [[InlineKeyboardButton("🎧 الاستماع للسورة", url=url)]]
        )
        await message.reply_text(
            f"📖 **سورة {display}**\n\n🎧 اضغط الزر بالأسفل للاستماع.",
            reply_markup=buttons,
            disable_web_page_preview=True,
        )
